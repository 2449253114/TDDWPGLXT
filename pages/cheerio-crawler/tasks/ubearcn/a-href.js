/**
 * 将对象数组中的每个URL用换行拼接成一个字符串
 * @param {Array} array - 包含对象的数组，每个对象有 "title" 和 "url" 属性
 * @returns {string} - 用换行拼接的URL字符串
 */
function concatenateUrls(array) {
  // 使用 map 方法从对象数组中提取每个对象的url属性
  const urls = array.map(obj => obj.url);

  // 使用 join 方法将urls数组中的元素用换行拼接成字符串
  const resultString = urls.join('\n');

  return resultString;
}


/**
 * 将多行字符串解析成包含标题和链接的对象数组
 * @param {string} inputString - 包含标题和链接的多行字符串
 * @returns {Array} - 包含对象的数组，每个对象有 "title" 和 "url" 属性
 */
function parseMultiLineString(inputString) {
  // 将输入字符串按行分割成数组
  const lines = inputString.split('\n');

  // 使用 map 方法处理每一行，返回相应的对象
  const resultArray = lines.map(line => {
    // 使用正则表达式匹配标题和链接
    const match = line.match(/^(.+?)\s+(http[^\s]+)/);

    // 如果匹配成功，则返回对象，否则返回 null
    return match ? {"title": match[1], "url": match[2]} : null;
  }).filter(Boolean); // 过滤掉匹配失败的行

  return resultArray;
}
